CREATE SCHEMA app;
CREATE SEQUENCE app.counter;
CREATE SEQUENCE app.small AS smallint START 5 INCREMENT BY -2 MINVALUE -100 MAXVALUE 50 CACHE 3 CYCLE;
CREATE SEQUENCE public.down INCREMENT BY -1;
CREATE SEQUENCE public.ticket_no AS integer START WITH 1000 CACHE 20;
COMMENT ON SEQUENCE public.ticket_no IS 'it''s a ticket';
CREATE TABLE app.orders (id serial, n bigint DEFAULT nextval('app.counter'), code int);
CREATE TABLE public.t (x int);
ALTER SEQUENCE public.down OWNED BY public.t.x;
CREATE TABLE public.tickets (
    id bigint GENERATED ALWAYS AS IDENTITY (START WITH 10 INCREMENT BY 5),
    no int DEFAULT nextval('ticket_no'),
    small smallint GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY -1 CYCLE)
);
