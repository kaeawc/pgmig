CREATE SCHEMA app;
CREATE SEQUENCE app.counter;
CREATE SEQUENCE app.orders_id_seq AS integer;
CREATE SEQUENCE app.small AS smallint INCREMENT BY -2 MINVALUE -100 MAXVALUE 50 START WITH 5 CACHE 3 CYCLE;
CREATE SEQUENCE public.down INCREMENT BY -1;
CREATE SEQUENCE public.ticket_no AS integer START WITH 1000 CACHE 20;
CREATE TABLE app.orders (
    id integer DEFAULT nextval('app.orders_id_seq'::regclass) NOT NULL,
    n bigint DEFAULT nextval('app.counter'::regclass),
    code integer
);
CREATE TABLE public.tickets (
    id bigint GENERATED ALWAYS AS IDENTITY (INCREMENT BY 5 START WITH 10) NOT NULL,
    no integer DEFAULT nextval('ticket_no'::regclass),
    small smallint GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY -1 CYCLE) NOT NULL
);
ALTER SEQUENCE app.orders_id_seq OWNED BY app.orders.id;
ALTER SEQUENCE public.down OWNED BY public.t.x;
COMMENT ON SEQUENCE public.ticket_no IS 'it''s a ticket';
